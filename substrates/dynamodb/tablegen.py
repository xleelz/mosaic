#!/usr/bin/env python3
"""Instantiate the per-table DynamoDB interface set from the substrate's generic operations.

    python3 substrates/dynamodb/tablegen.py --table orders [--table events] \
        [--component dynamodb] [--target dynamodb] [--id my-tables] > tables.yaml

For each table it writes <table>-get, -put, -update, -delete, -query and the conditional set
<table>-put-if, -update-if, -delete-if and -incr-if (the conditional-write set one
build's areas converged on). Each one calls the generic
operation on --target (the imported component, e.g. ddb/dynamodb) with `table` filled in, so
there is one implementation. --component is where the interfaces live (default: dynamodb,
the component itself when the substrate is imported without `as:`). The tables also need an
entry in config `dynamodb-tables`.
"""
import argparse
import json
import sys

KEY = {"pk": {"type": "string"}, "sk": {"type": "string", "default": ""}}
COND = lambda default: {"type": "string", "default": default, "description": "CEL over row (null when absent): the ConditionExpression"}

OPS = [
    # name, generic op, summary, extra properties, required
    ("get", "get", "GetItem on {t}", {}, ["pk"]),
    ("put", "put", "PutItem on {t}", {"item": {"type": "object"}}, ["pk", "item"]),
    ("update", "update", "UpdateItem SET on {t} (creates a missing item)", {"item": {"type": "object"}}, ["pk", "item"]),
    ("delete", "delete", "DeleteItem on {t}", {}, ["pk"]),
    ("query", "query", "Query {t} or one of its GSIs", {
        "index": {"type": "string", "default": ""}, "sk_begins_with": {"type": "string", "default": ""},
        "sk_between": {"type": "array", "default": [], "maxItems": 2}, "forward": {"type": "boolean", "default": True},
        "limit": {"type": "integer", "default": 0, "minimum": 0}}, ["pk"]),
    ("put-if", "put-if", "PutItem on {t} with a ConditionExpression; a failed condition is condition_failed 412",
     {"item": {"type": "object"}, "cond": COND("true")}, ["pk", "item"]),
    ("update-if", "update-if", "UpdateItem on {t} with a ConditionExpression; a missing row fails the default condition",
     {"item": {"type": "object"}, "cond": COND("row != null")}, ["pk", "item"]),
    ("delete-if", "delete-if", "DeleteItem on {t} with a ConditionExpression", {"cond": COND("true")}, ["pk"]),
    ("incr-if", "incr-if", "UpdateItem ADD on {t} with a ConditionExpression (atomic counters)",
     {"delta": {"type": "object"}, "cond": COND("true")}, ["pk", "delta"]),
]
ERRORS = {
    "get": ["resource_not_found"], "put": ["resource_not_found"], "update": ["resource_not_found"],
    "delete": ["resource_not_found"], "query": ["resource_not_found", "validation_error"],
}
STATUS = {"resource_not_found": 400, "validation_error": 400, "condition_failed": 412}


def interfaces(table, component, target):
    for name, op, summary, extra, required in OPS:
        props = dict(KEY)
        if name == "query":
            props = {"pk": KEY["pk"]}
        props.update(extra)
        errs = ERRORS.get(op, ["resource_not_found", "condition_failed"])
        yield {
            "component": component,
            "name": f"{table}-{name}",
            "kind": "rpc",
            "summary": summary.format(t=table),
            "sources": ["substrates/dynamodb/dynamodb.yaml"],
            "latency_ms": 0,
            "request": {"type": "object", "required": required, "properties": props},
            "errors": [dict(code=c, status=STATUS[c], **({"retryable": False} if c == "condition_failed" else {})) for c in errs],
            "behavior": [
                {"call": f"{target}.{op}", "input": f"= merge(input, {{'table': '{table}'}})", "as": "r"},
                {"return": "= vars.r.value"},
            ],
        }


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--table", action="append", required=True)
    ap.add_argument("--component", default="dynamodb")
    ap.add_argument("--target", default="dynamodb")
    ap.add_argument("--id", default=None)
    a = ap.parse_args()
    doc = {"schema_version": 1}
    if a.id:
        doc["id"] = a.id
    doc["interfaces"] = [f for t in a.table for f in interfaces(t, a.component, a.target)]
    sys.stdout.write("# Generated by substrates/dynamodb/tablegen.py " + " ".join(f"--table {t}" for t in a.table)
                     + f" --component {a.component} --target {a.target}; do not edit.\n")
    # JSON is YAML; one interface per line keeps diffs readable.
    sys.stdout.write("schema_version: 1\n")
    if a.id:
        sys.stdout.write(f"id: {a.id}\n")
    sys.stdout.write("interfaces:\n")
    for f in doc["interfaces"]:
        sys.stdout.write("  - " + json.dumps(f, separators=(", ", ": ")) + "\n")


if __name__ == "__main__":
    main()
