#!/usr/bin/env python3
"""Merge the distributed area's part files into fragments/distributed.yaml.

Each part is a fragment document (schema_version, id, then entity lists). The merge is
textual, so YAML 1.2 semantics are kept (PyYAML would turn the `on:` key into a boolean):
the body of each top-level list is concatenated in part order.
Usage: python3 -I build.py
"""
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "fragments", "distributed.yaml")
KINDS = ["configs", "schemas", "components", "interfaces", "links", "flows", "fixtures", "scenarios"]
TOP = re.compile(r"^([a-z_]+):(.*)$")


def main() -> None:
    merged = {k: [] for k in KINDS}
    for part in sorted(glob.glob(os.path.join(HERE, "p*.yaml"))):
        cur = None
        for line in open(part):
            m = TOP.match(line)
            if m:
                key, rest = m.group(1), m.group(2).strip()
                if key in ("schema_version", "id", "name", "description"):
                    cur = None
                    continue
                if key not in KINDS:
                    sys.exit(f"{part}: unexpected top-level key {key}")
                if rest not in ("", "[]"):
                    sys.exit(f"{part}: {key} must be a block list")
                cur = key
                continue
            if cur is not None:
                merged[cur].append(line)
    with open(OUT, "w") as f:
        f.write("# distributed area fragment (vllm v0.32.0). Generated by gen/distributed/build.py\n")
        f.write("# from gen/distributed/p*.yaml; edit the parts, not this file.\n")
        f.write("schema_version: 1\nid: vllm\n")
        for k in KINDS:
            body = [l for l in merged[k]]
            if any(l.strip() and not l.lstrip().startswith("#") for l in body):
                f.write(f"\n{k}:\n")
                f.writelines(body)


if __name__ == "__main__":
    main()
