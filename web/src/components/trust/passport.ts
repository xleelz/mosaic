// What the model passport says, derived from stored evidence and nothing else. If a figure
// isn't stored, the words say so: this file never fills a gap with a guess.
//
// Only type imports (and sibling .ts files) here: node --test runs this file with type stripping.

import type { Evidence } from "../../lib/api/types";
import { countFidelity, type FidelityCounts } from "./fidelity.ts";

export const NOT_BENCHMARKED = "Not benchmarked";

export const USE_IT_TO = "find where things live, and form hypotheses you check in code.";
export const DONT_USE_IT_TO = "conclude that the system does or doesn't do something.";
export const SELF_CHECK_CAPTION = "These scenarios were written alongside the model, so they show consistency, not accuracy.";

/** The viewed revision: a number, or null for the draft. */
export type ViewedRevision = number | null;

export interface PassportFacts {
  /** The chip's one line. */
  chip: string;
  built: string;
  blind: {
    /** "30% of steps" or NOT_BENCHMARKED. */
    headline: string;
    /** The raw counts behind the headline, when measured. */
    detail?: string;
    /** "measured on r3" and whether that's the viewed revision. */
    measured?: string;
    stale: boolean;
  };
  mechanisms: {
    counts: FidelityCounts;
    /** Share of mechanisms fully modeled, 0 to 100; null with no list. */
    modeledPct: number | null;
    measured?: string;
    stale: boolean;
  };
  source?: string;
}

function pct(n: number, of: number): number {
  return Math.round((n / of) * 100);
}

/** Whether a figure measured on `measured` belongs to another revision than the one viewed. */
function measuredWords(measured: number, viewed: ViewedRevision): { measured: string; stale: boolean } {
  if (viewed === null) return { measured: `measured on r${measured}, not on this draft`, stale: true };
  if (viewed === measured) return { measured: `measured on r${measured}`, stale: false };
  if (viewed > measured) return { measured: `measured on r${measured}, not re-measured`, stale: true };
  return { measured: `measured on r${measured}, a later revision`, stale: true };
}

export function builtWords(builtBy: string | undefined): string {
  if (builtBy === "generated") return "Generated by agents from source. No end-to-end human review is on record.";
  if (builtBy === "handwritten") return "Written by hand.";
  return "Nothing records how this model was built.";
}

/**
 * Facts for a passport. `evidence` is null when none is stored; undefined isn't a value here,
 * since the component shows a loading state until it's known.
 */
export function passportFacts(evidence: Evidence | null, viewed: ViewedRevision): PassportFacts {
  const blind = evidence?.blind;
  const list = evidence?.mechanisms;
  const counts = countFidelity(list?.items ?? []);
  const modeledPct = counts.total > 0 ? pct(counts.modeled, counts.total) : null;

  const blindWords = blind ? measuredWords(blind.measured_on_revision, viewed) : undefined;
  const measuredBlind = !!blind && blind.steps_total > 0;
  const blindHeadline = measuredBlind ? `${pct(blind.steps_passed, blind.steps_total)}% of steps` : NOT_BENCHMARKED;
  const detail = measuredBlind
    ? [
        `${blind.steps_passed} of ${blind.steps_total} steps`,
        blind.cases_total > 0 ? `${blind.cases_passed} of ${blind.cases_total} cases` : "",
        blind.oracle_total > 0 ? `${blind.oracle_passed} of ${blind.oracle_total} oracle tests` : "",
        blind.oracle_untranslatable ? `${blind.oracle_untranslatable} oracle tests couldn't be translated` : "",
      ]
        .filter(Boolean)
        .join(", ")
    : undefined;

  const listWords = list && counts.total > 0 ? measuredWords(list.measured_on_revision, viewed) : undefined;

  const chipParts: string[] = [];
  if (evidence?.built_by === "generated") chipParts.push("Generated model");
  else if (evidence?.built_by === "handwritten") chipParts.push("Hand-written model");
  if (measuredBlind) {
    chipParts.push(`blind benchmark ${blindHeadline}${blindWords?.stale ? ` (r${blind.measured_on_revision})` : ""}`);
  } else {
    chipParts.push(NOT_BENCHMARKED);
  }
  if (modeledPct !== null) chipParts.push(`${modeledPct}% of mechanisms modeled${listWords?.stale ? ` (r${list!.measured_on_revision})` : ""}`);

  const repo = evidence?.source?.repo;
  const commit = evidence?.source?.commit;
  return {
    chip: chipParts.join(" · "),
    built: builtWords(evidence?.built_by),
    blind: { headline: blindHeadline, detail, measured: measuredBlind ? blindWords?.measured : undefined, stale: measuredBlind && !!blindWords?.stale },
    mechanisms: { counts, modeledPct, measured: listWords?.measured, stale: !!listWords?.stale },
    source: repo || commit ? [repo, commit ? `@ ${commit.slice(0, 7)} (pinned)` : ""].filter(Boolean).join(" ") : undefined,
  };
}

/** A self-check result in the words the plan requires: it always carries "self-checks", never "all pass". */
export function selfCheckWords(report: { total: number; failed: number } | null, scenarios: number | undefined): string {
  if (report) return `${report.total - report.failed} of ${report.total} self-checks pass`;
  if (scenarios === undefined) return "Not run yet";
  return scenarios === 0 ? "No scenarios to check" : `Not run yet (${scenarios} ${scenarios === 1 ? "scenario" : "scenarios"})`;
}

/** The revision a selector shows: a number, the latest (null if it has none yet), or null for the draft. */
export function viewedRevision(rev: string | undefined, latest: number | undefined): ViewedRevision {
  if (rev && /^\d+$/.test(rev)) return Number(rev);
  if (rev === "draft" || !latest) return null;
  return latest;
}
